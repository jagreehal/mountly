import { readFile, rm, writeFile } from "node:fs/promises";
import { basename, isAbsolute, join, resolve } from "node:path";
import { parseAst, type BuildEnvironment, type Plugin, type UserConfig } from "vite";
import { MCP_APP_MANIFEST_FILE, writeMcpAppManifest } from "../artifact/index.js";
import type { McpAppArtifact } from "../artifact/index.js";
import { buildMcpResourceFromSource } from "../build/index.js";
import type { BuildSelfContainedOptions } from "../build/index.js";

export interface MountlyMcpViewOptions extends Omit<
  BuildSelfContainedOptions,
  "entry" | "output" | "cssEntry"
> {
  entry: string;
  output?: string;
  cleanIntermediate?: boolean;
}

export interface MountlyMcpViewsOptions {
  apps: ReadonlyArray<MountlyMcpViewOptions>;
  /** Defaults to `<outDir>/mountly-mcp.manifest.json`; false disables it. */
  manifest?: string | false;
  /**
   * Also write every View, HTML included, as an ES module, for a server that
   * cannot read files — Cloudflare Workers, say: `import views from
   * "./dist/mountly-mcp.views.js"`, then `views.map((artifact) => ({ artifact }))`.
   * `true` writes `<outDir>/mountly-mcp.views.js`; a string names the path.
   */
  module?: string | boolean;
}

export const MCP_APP_VIEWS_MODULE_FILE = "mountly-mcp.views.js";

/** `mountly-mcp.views.js` and the declaration beside it. */
async function writeViewsModule(path: string, artifacts: ReadonlyArray<McpAppArtifact>) {
  const views = await Promise.all(
    artifacts.map(async ({ name, uri, declaration, htmlPath }) => ({
      name,
      uri,
      declaration,
      html: await readFile(htmlPath, "utf8"),
    })),
  );
  await writeFile(
    path,
    `// Generated by mountly-mcp. Do not edit.\nexport default ${JSON.stringify(views, null, 2)};\n`,
    "utf8",
  );
  await writeFile(
    // `views.mjs` pairs with `views.d.mts`, which is where TypeScript looks.
    path.replace(/\.(m?)js$/, ".d.$1ts"),
    `// Generated by mountly-mcp. Do not edit.\nimport type { McpAppSource } from "mountly-mcp/artifact";\ndeclare const views: ReadonlyArray<McpAppSource>;\nexport default views;\n`,
    "utf8",
  );
}

export type MountlyMcpViteOptions = MountlyMcpViewOptions | MountlyMcpViewsOptions;

export interface MountlyMcpViteApi {
  apps: ReadonlyArray<MountlyMcpViewOptions>;
  manifest?: string | false;
}

function isCollection(options: MountlyMcpViteOptions): options is MountlyMcpViewsOptions {
  return "apps" in options;
}

function safeBuildName(name: string, index: number): string {
  const safe = name.replace(/[^a-zA-Z0-9_-]/g, "_");
  return `mountly_mcp_${index}_${safe || "app"}`;
}

function outputPath(root: string, outDir: string, app: MountlyMcpViewOptions): string {
  if (!app.output) return join(outDir, `${basename(app.name)}.html`);
  return isAbsolute(app.output) ? app.output : resolve(root, app.output);
}

/**
 * `new Worker(new URL("./w.ts", import.meta.url), …)` emits the worker as its own
 * file, which a `ui://` resource cannot serve: the View is one HTML document.
 * Rewrite each to Vite's `?worker&inline` import, which bundles the worker into
 * the View and starts it from a blob URL — so the host's CSP must allow
 * `worker-src blob:`. Workers built any other way are left alone; `mountly-mcp
 * doctor` points them out.
 */
type Node = Record<string, any>;
type Edit = [start: number, end: number, text: string];

function isImportMetaUrl(node: Node | undefined): boolean {
  return (
    node?.type === "MemberExpression" &&
    node.object?.type === "MetaProperty" &&
    node.object.meta?.name === "import" &&
    node.object.property?.name === "meta" &&
    node.property?.name === "url"
  );
}

function stringValue(node: Node | undefined): string | undefined {
  if (node?.type === "Literal" && typeof node.value === "string") return node.value;
  if (node?.type === "TemplateLiteral" && node.expressions.length === 0) {
    return node.quasis[0]?.value?.cooked;
  }
  return undefined;
}

/**
 * The edits for every worker call in one script. Parsed, not pattern-matched:
 * the same characters in a comment or a string are not a call.
 */
function workerEdits(
  script: string,
  lang: "js" | "jsx" | "ts" | "tsx",
  offset: number,
  imports: string[],
  count: { n: number },
): Edit[] {
  const edits: Edit[] = [];
  const walk = (node: unknown): void => {
    if (Array.isArray(node)) return node.forEach(walk);
    if (!node || typeof node !== "object") return;
    const n = node as Node;
    if (
      n.type === "NewExpression" &&
      (n.callee?.name === "Worker" || n.callee?.name === "SharedWorker")
    ) {
      const [url, options] = n.arguments ?? [];
      const path =
        url?.type === "NewExpression" && url.callee?.name === "URL"
          ? stringValue(url.arguments?.[0])
          : undefined;
      if (path !== undefined && isImportMetaUrl(url.arguments?.[1])) {
        const id = `__mountlyMcpWorker${count.n++}`;
        const query = n.callee.name === "SharedWorker" ? "sharedworker" : "worker";
        imports.push(`import ${id} from ${JSON.stringify(`${path}?${query}&inline`)};`);
        // The wrapper takes the options object (it reads `name`) as its only
        // argument. Without one, the whole call goes, trailing comma included.
        const end = options ? options.start : n.end;
        const text = options ? `new ${id}(` : `new ${id}()`;
        // Keep the span's line breaks, so every later line keeps its number.
        const breaks = script.slice(n.start, end).split("\n").length - 1;
        edits.push([offset + n.start, offset + end, text + "\n".repeat(breaks)]);
      }
    }
    for (const key in n) walk(n[key]);
  };
  walk(parseAst(script, { lang }));
  return edits;
}

function langOf(file: string, attributes = ""): "js" | "jsx" | "ts" | "tsx" {
  const lang =
    /\blang\s*=\s*["']?(tsx|ts|jsx|js)\b/.exec(attributes)?.[1] ??
    /\.([cm]?[jt]sx?)$/.exec(file)?.[1];
  if (lang === "tsx" || lang === "jsx") return lang;
  return lang && /ts$/.test(lang) ? "ts" : "js";
}

/**
 * Rewrite a module's worker calls. In a `.vue` or `.svelte` file each
 * `<script>` is parsed on its own, and its imports go inside that block —
 * anything outside it is not script, and the compiler drops it.
 */
export function inlineWorkers(code: string, file = "view.ts"): string | null {
  if (!code.includes("import.meta")) return null;
  const edits: Edit[] = [];
  const count = { n: 0 };
  try {
    if (/\.(vue|svelte)$/.test(file)) {
      for (const block of code.matchAll(/(<script\b([^>]*)>)([\s\S]*?)<\/script>/g)) {
        const start = (block.index ?? 0) + (block[1]?.length ?? 0);
        const imports: string[] = [];
        edits.push(...workerEdits(block[3] ?? "", langOf(file, block[2]), start, imports, count));
        if (imports.length) edits.push([start, start, imports.join("")]);
      }
    } else {
      const imports: string[] = [];
      edits.push(...workerEdits(code, langOf(file), 0, imports, count));
      if (imports.length) edits.push([0, 0, imports.join("")]);
    }
  } catch {
    // Unparseable here means some later plugin owns this syntax; leave it to Vite.
    return null;
  }
  if (!edits.length) return null;
  let out = code;
  // Right to left, so earlier offsets stay valid.
  for (const [start, end, text] of edits.sort((a, b) => b[0] - a[0] || b[1] - a[1])) {
    out = out.slice(0, start) + text + out.slice(end);
  }
  return out;
}

/**
 * Build one or many independent MCP Apps Views. Each View is a Vite build
 * environment, so frameworks and CSS remain isolated while callers configure
 * the collection once.
 */
export function mountlyMcpViews(options: MountlyMcpViteOptions): Plugin {
  const configuredApps = isCollection(options) ? [...options.apps] : [options];
  const selectedForDev = process.env.MOUNTLY_MCP_SELECTED_APP;
  const apps = selectedForDev
    ? configuredApps.filter((app) => app.name === selectedForDev)
    : configuredApps;
  const manifestOption = isCollection(options) ? options.manifest : undefined;
  const moduleOption = isCollection(options) ? options.module : undefined;
  if (typeof moduleOption === "string" && !/\.m?js$/.test(moduleOption)) {
    throw new Error(
      `mountly-mcp: module must name a .js or .mjs file (received '${moduleOption}')`,
    );
  }
  if (apps.length === 0) throw new Error("mountly-mcp: apps must contain at least one View");

  const names = new Set<string>();
  const uris = new Set<string>();
  for (const app of apps) {
    if (!app.uri.startsWith("ui://")) {
      throw new Error(
        `mountly-mcp: UI resource uri must use the 'ui://' scheme (received '${app.uri}')`,
      );
    }
    if (names.has(app.name)) throw new Error(`mountly-mcp: duplicate app name '${app.name}'`);
    if (uris.has(app.uri)) throw new Error(`mountly-mcp: duplicate app uri '${app.uri}'`);
    names.add(app.name);
    uris.add(app.uri);
  }

  const environments = apps.map((app, index) => ({
    app,
    name: safeBuildName(app.name, index),
    jsFile: `view-${index}-${basename(app.name)}.js`,
    cssFile: `view-${index}-${basename(app.name)}.css`,
  }));
  const byEnvironment = new Map(environments.map((environment) => [environment.name, environment]));
  const emitted = new Map<
    string,
    { js?: string; css?: string; jsFile?: string; cssFile?: string; names: string[] }
  >();
  const artifacts = new Map<string, McpAppArtifact>();
  let root = process.cwd();
  let outDir = resolve(root, "dist");
  let manifestWritten = false;

  function currentEnvironment(context: unknown) {
    const name = (context as { environment?: { name?: string } }).environment?.name;
    return (
      (name ? byEnvironment.get(name) : undefined) ??
      (environments.length === 1 ? environments[0] : undefined)
    );
  }

  const plugin: Plugin = {
    name: "mountly-mcp-views",
    api: {
      // The CLI consumes this documented plugin interface instead of scraping
      // Vite's resolved build settings.
      mountlyMcp: { apps: configuredApps, manifest: manifestOption } satisfies MountlyMcpViteApi,
    },
    // After Vite core plugins: css-post writes the stylesheet in its own
    // closeBundle, and this plugin has to see the file to inline it.
    enforce: "post",
    // Only meaningful during `vite build`; a dev server has no bundle to emit.
    apply: "build",

    // Before TypeScript is stripped and before Vite's own worker plugin claims
    // the `new URL(…)` and emits a separate file.
    transform: {
      order: "pre",
      handler(code, id) {
        if (id.includes("/node_modules/") || id.includes("?")) return null;
        const out = inlineWorkers(code, id);
        return out === null ? null : { code: out, map: null };
      },
    },

    config(config, env): UserConfig {
      const first = environments[0];
      if (!first) throw new Error("mountly-mcp: configure at least one app");
      return {
        // An inline worker is one blob, so its own bundle must be one file too.
        ...(config.worker?.format ? {} : { worker: { format: "iife" as const } }),
        // Vite's lib mode leaves `process.env.NODE_ENV` for a consuming bundler
        // to replace. There isn't one — the bundle is inlined into HTML and run
        // in a sandboxed iframe, where `process` is undefined and React and Vue
        // throw on their first environment check.
        define: { "process.env.NODE_ENV": JSON.stringify(env.mode) },
        // Legacy `vite build` builds one environment. Preserve that zero-config
        // path for single-View projects; multi-View projects use
        // `mountly-mcp build`, which drives the environments below.
        build: {
          lib: {
            entry: first.app.entry,
            // IIFE so the bundle inlines into a single <script> with no import
            // graph left to resolve inside the sandboxed iframe.
            formats: ["iife"] as const,
            name: "__mountlyMcpEntry0",
            fileName: () => first.jsFile,
            // Named explicitly: otherwise a lib build derives the stylesheet
            // name from package.json and fails outright when there isn't one.
            cssFileName: first.cssFile.replace(/\.css$/, ""),
          },
          // One stylesheet to inline; per-chunk CSS would strand imports.
          cssCodeSplit: false,
        },
        builder: {
          sharedPlugins: true,
          async buildApp(builder) {
            for (const environment of environments) {
              const target = builder.environments[environment.name] as BuildEnvironment | undefined;
              if (!target)
                throw new Error(`mountly-mcp: missing Vite environment '${environment.name}'`);
              await builder.build(target);
            }
          },
        },
        environments: Object.fromEntries(
          environments.map((environment, index) => [
            environment.name,
            {
              // A custom environment defaults to a server consumer, which
              // externalizes node_modules — React and Vue would become bare
              // globals and the view would die on `vue is not defined`. A
              // `ui://` resource has no import graph at runtime, so everything
              // must be bundled in.
              consumer: "client" as const,
              resolve: { noExternal: true as const },
              build: {
                emptyOutDir: index === 0,
                lib: {
                  entry: environment.app.entry,
                  formats: ["iife"] as const,
                  name: `__mountlyMcpEntry${index}`,
                  fileName: () => environment.jsFile,
                  cssFileName: environment.cssFile.replace(/\.css$/, ""),
                },
                cssCodeSplit: false,
              },
            },
          ]),
        ),
      };
    },

    configResolved(config) {
      root = config.root;
      outDir = resolve(config.root, config.build.outDir);
    },

    buildStart() {
      const name = (this as { environment?: { name?: string } }).environment?.name;
      if (apps.length > 1 && !byEnvironment.has(String(name))) {
        this.error(
          "mountly-mcp: multi-View builds require 'mountly-mcp build' (or 'vite build --app') so Vite builds every environment",
        );
      }
    },

    generateBundle: {
      order: "post",
      handler(_outputOptions, bundle) {
        const environment = currentEnvironment(this);
        if (!environment) return;
        const chunk =
          bundle[environment.jsFile] ??
          Object.values(bundle).find((item) => item.type === "chunk" && item.isEntry);
        const cssAsset =
          bundle[environment.cssFile] ??
          Object.values(bundle).find(
            (item) => item.type === "asset" && item.fileName.endsWith(".css"),
          );
        emitted.set(environment.name, {
          js: chunk && "code" in chunk ? chunk.code : undefined,
          css: cssAsset && "source" in cssAsset ? cssAsset.source.toString() : undefined,
          jsFile: chunk?.fileName,
          cssFile: cssAsset?.fileName,
          names: Object.keys(bundle),
        });
      },
    },

    async closeBundle() {
      const environment = currentEnvironment(this);
      if (!environment || artifacts.has(environment.name)) return;
      const source = emitted.get(environment.name);
      if (source?.js === undefined) {
        this.error(
          `mountly-mcp: the build emitted no ${environment.jsFile} for '${environment.app.entry}'. Emitted: ${source?.names.join(", ") || "nothing"}`,
        );
        return;
      }
      const {
        entry: _entry,
        output: _output,
        cleanIntermediate = true,
        ...resourceOptions
      } = environment.app;
      const result = await buildMcpResourceFromSource({
        ...resourceOptions,
        js: source.js,
        css: source.css,
        output: outputPath(root, outDir, environment.app),
      });
      artifacts.set(environment.name, result.artifact);
      if (cleanIntermediate) {
        if (source.jsFile) await rm(join(outDir, source.jsFile), { force: true });
        if (source.cssFile) await rm(join(outDir, source.cssFile), { force: true });
      }
      this.info?.(`mountly-mcp: ${environment.app.uri} → ${result.htmlPath}`);

      if (manifestWritten || artifacts.size !== environments.length) return;
      manifestWritten = true;
      const all = environments.map((item) => artifacts.get(item.name) as McpAppArtifact);
      const at = (path: string) => (isAbsolute(path) ? path : resolve(root, path));
      if (manifestOption !== false) {
        const path = manifestOption ? at(manifestOption) : join(outDir, MCP_APP_MANIFEST_FILE);
        await writeMcpAppManifest(path, all);
        this.info?.(`mountly-mcp: manifest → ${path}`);
      }
      if (moduleOption) {
        const path =
          typeof moduleOption === "string"
            ? at(moduleOption)
            : join(outDir, MCP_APP_VIEWS_MODULE_FILE);
        await writeViewsModule(path, all);
        this.info?.(`mountly-mcp: views module → ${path}`);
      }
    },
  };

  return plugin;
}
